#[test]
/// Проверяет литовские и латышские буквы на читаемых примерах.
fn decodes_baltic_text_and_rejects_undefined_octets() {
    assert_eq!(decode(b"\xc0ietuva"), Ok("Ąietuva".to_owned()));
    assert_eq!(decode(b"\xd4\xd9\xe0\x9d"), Ok("ŌŁą¯".to_owned()));
    for byte in [
        0x81, 0x83, 0x88, 0x8a, 0x8c, 0x90, 0x98, 0x9a, 0x9c, 0x9f, 0xa1, 0xa5,
    ] {
        assert!(decode(&[byte]).is_err(), "undefined octet {byte:#04x}");
    }
}
