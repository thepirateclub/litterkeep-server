//! Декодирование MIME charset KOI8-R по таблице RFC 1489.

/// Преобразует каждый октет без потери ASCII/control и кириллических данных.
pub(super) fn decode(bytes: &[u8]) -> String {
    bytes.iter().copied().map(decode_octet).collect()
}

/// Ищет octet в определённой RFC верхней половине таблицы.
fn decode_octet(octet: u8) -> char {
    match octet {
        0x00..=0x7f => char::from(octet),
        0x80..=0xff => {
            let offset = usize::from(octet.saturating_sub(0x80));
            UPPER_HALF
                .get(offset)
                .copied()
                .unwrap_or(char::REPLACEMENT_CHARACTER)
        }
    }
}

