#[test]
/// Проверяет декодирование естественного вьетнамского текста без нормализации.
fn preserves_combining_sequences_used_by_vietnamese_text() {
    assert_eq!(
        decode(b"Ti\xea\xecng Vi\xea\xf2t"),
        Ok("Tiê\u{0301}ng Viê\u{0323}t".to_owned())
    );
    assert_eq!(
        decode(b"\xd2\xde\xec\xf2"),
        Ok("\u{0309}\u{0303}\u{0301}\u{0323}".to_owned())
    );
}
