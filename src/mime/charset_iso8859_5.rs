//! Полная таблица преобразования MIME charset ISO-8859-5 (кириллица).

/// Декодирует ISO-8859-5, сохраняя управляющие C1 значения как Unicode controls.
///
/// Протокольные данные остаются байтами до выбора charset; после этого каждый
/// октет имеет однозначный mapping. Декодер не применяет Windows-1251 правила.
pub(super) fn decode(bytes: &[u8]) -> String {
    bytes.iter().copied().map(decode_byte).collect()
}

/// Преобразует один октет с отдельной таблицей для печатной верхней половины.
fn decode_byte(byte: u8) -> char {
    match byte {
        0x00..=0x9f => char::from(byte),
        0xa0..=0xff => {
            let offset = usize::from(byte.saturating_sub(0xa0));
            UPPER_HALF
                .get(offset)
                .copied()
                .unwrap_or(char::REPLACEMENT_CHARACTER)
        }
    }
}

