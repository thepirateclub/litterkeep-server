#[test]
fn maps_every_octet_to_the_rfc_1489_unicode_table() {
    let octets: Vec<u8> = (0_u8..=u8::MAX).collect();
    let actual = decode(&octets);
    let expected: String = (0_u8..=0x7f)
        .map(char::from)
        .chain(RFC_UPPER_HALF)
        .collect();

    assert_eq!(actual, expected);
}

#[test]
fn canonical_name_alias_and_russian_sample_decode() {
    assert_eq!(Charset::parse("KOI8-R"), Ok(Charset::Koi8R));
    assert_eq!(Charset::parse("csKOI8R"), Ok(Charset::Koi8R));
    assert_eq!(
        Charset::Koi8R.decode(b"\xf0\xd2\xc9\xd7\xc5\xd4"),
        Ok("Привет".to_owned())
    );
}
