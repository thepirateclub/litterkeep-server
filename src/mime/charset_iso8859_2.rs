//! Полная таблица преобразования MIME charset ISO-8859-2.

/// Декодирует каждый октет ISO-8859-2 в соответствующий Unicode scalar value.
///
/// Первые 160 значений совпадают с ASCII и C1 control block, поэтому таблица
/// хранит только отображение диапазона A0..FF. Поиск через `get` намеренно
/// сохраняет безопасную обработку даже при изменении диапазонов входа.
pub(super) fn decode(bytes: &[u8]) -> Result<String, &'static str> {
    bytes.iter().copied().map(decode_byte).collect()
}

/// Преобразует один байт ISO-8859-2 без прямой индексации массива.
fn decode_byte(byte: u8) -> Result<char, &'static str> {
    match byte {
        0x00..=0x9f => Ok(char::from(byte)),
        0xa0..=0xff => {
            let offset = usize::from(byte.saturating_sub(0xa0));
            UPPER_HALF
                .get(offset)
                .copied()
                .ok_or("ISO-8859-2 table offset is invalid")
        }
    }
}

