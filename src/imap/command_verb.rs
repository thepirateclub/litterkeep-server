//! Сопоставление IMAP verb на границе недоверенного сетевого текста.

/// Имя команды в виде Enum до разбора её аргументов.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum Verb {
    Capability,
    Namespace,
    Enable,
    StartTls,
    Login,
    Authenticate,
    Append,
    Logout,
    Noop,
    Idle,
    Create,
    Delete,
    Rename,
    Subscribe,
    Unsubscribe,
    Lsub,
    Status,
    Check,
    Close,
    Unselect,
    Copy,
    Move,
    Expunge,
    List,
    Select,
    Examine,
    Fetch,
    Store,
    Search,
    Uid,
    Unsupported,
}

/// Единственная точка сравнения сетевого verb без учёта регистра.
pub(super) fn parse_verb(text: &str) -> Verb {
    match text.to_ascii_uppercase().as_str() {
        "CAPABILITY" => Verb::Capability,
        "NAMESPACE" => Verb::Namespace,
        "ENABLE" => Verb::Enable,
        "STARTTLS" => Verb::StartTls,
        "LOGIN" => Verb::Login,
        "AUTHENTICATE" => Verb::Authenticate,
        "APPEND" => Verb::Append,
        "LOGOUT" => Verb::Logout,
        "NOOP" => Verb::Noop,
        "IDLE" => Verb::Idle,
        "CREATE" => Verb::Create,
        "DELETE" => Verb::Delete,
        "RENAME" => Verb::Rename,
        "SUBSCRIBE" => Verb::Subscribe,
        "UNSUBSCRIBE" => Verb::Unsubscribe,
        "LSUB" => Verb::Lsub,
        "STATUS" => Verb::Status,
        "CHECK" => Verb::Check,
        "CLOSE" => Verb::Close,
        "UNSELECT" => Verb::Unselect,
        "COPY" => Verb::Copy,
        "MOVE" => Verb::Move,
        "EXPUNGE" => Verb::Expunge,
        "LIST" => Verb::List,
        "SELECT" => Verb::Select,
        "EXAMINE" => Verb::Examine,
        "FETCH" => Verb::Fetch,
        "STORE" => Verb::Store,
        "SEARCH" => Verb::Search,
        "UID" => Verb::Uid,
        _ => Verb::Unsupported,
    }
}
